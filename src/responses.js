function getScenarioResponse(intent, language) {
  const lang = language === "kz" ? "kz" : "ru";
  return SCENARIOS[intent]?.[lang] || SCENARIOS[intent]?.ru || null;
}

function appendSoftQuestion(text, language) {
  if (!text) return text;
  if (text.includes("?")) return text;

  const closers = {
    ru: "\n\nПодскажите, чем могу помочь дальше?",
    kz: "\n\nӘрі қарай қалай көмектесе аламын?"
  };
  return text + (closers[language] || closers.ru);
}

